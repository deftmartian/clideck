import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { chromium, firefox } from 'playwright-core';
const browserType = process.env.BROWSER === 'firefox' ? firefox : chromium;
const launchOptions = { headless: true, ...(browserType === chromium ? {executablePath: process.env.CHROMIUM_PATH || chromium.executablePath(), args:['--no-sandbox']} : {}) };
const require = createRequire(import.meta.url);
const { HeadlessServer } = require(process.env.CLIDECK_PACKAGE_ROOT ? join(process.env.CLIDECK_PACKAGE_ROOT, 'src/server') : '../src/server');
const dir = mkdtempSync(join(tmpdir(), 'clideck-browser-port-'));
const server = new HeadlessServer({ port: 0, dataDir: dir, cwd: dir, requireProtocol: true });
let browser;
try {
  const { httpUrl } = await server.listen();
  const fixture = `process.stdin.setRawMode(true);process.stdin.resume();process.stdin.on('data',d=>{});setTimeout(()=>{process.stdout.write(Array.from({length:180},(_,i)=>'fixture row '+i+'\\r\\n').join('')+'\\x1b[>0q');},250);`;
  const session = server.startSession({ provider: { id: 'shell', supportsAsk: false, statusFromActivity: true, activityIdleMs: 50,
    createLaunch: () => ({ command: process.execPath, args: ['-e', fixture] }) }, cwd: dir, name: 'Mobile fixture', cols: 40, rows: 30, port:server.port }, true);
  const inputs = [];
  const write = session.terminal.write.bind(session.terminal);
  session.terminal.write = data => { inputs.push(data); write(data); };
  browser = await browserType.launch(launchOptions);
  const page = await browser.newPage({ viewport:{width:390,height:844}, ...(browserType === chromium && {isMobile:true}), hasTouch:true });
  await page.addInitScript(() => {
    window.copiedSelections=[];
    Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>window.copiedSelections.push(text)}});
  });
  const errors=[]; page.on('pageerror', error=>errors.push(error.message));
  await page.goto(httpUrl);
  await page.locator('#conn-text').filter({hasText:'live'}).waitFor();
  await page.getByRole('button',{name:'Sessions',exact:true}).click();
  await page.locator(`.row[data-id="${session.id}"]`).click();
  await page.waitForFunction(()=>document.querySelector('.xterm-screen'));
  await page.getByRole('textbox',{name:'Prompt',exact:true}).waitFor();
  const draft=page.getByRole('textbox',{name:'Prompt',exact:true});
  await draft.fill('first line\nsecond line');
  const before=inputs.length;
  await page.getByRole('button',{name:'Send',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#mobile-composer-text').value==='');
  await page.waitForTimeout(200);
  const submitted=inputs.slice(before).filter(s=>s.includes('first line'));
  assert.equal(submitted.length,1,'multiline prompt sent exactly once');
  assert.match(submitted[0],/first line[\s\S]*second line[\s\S]*\r$/);
  await page.reload();
  await page.locator('#conn-text').filter({hasText:'live'}).waitFor();
  await page.waitForTimeout(300);
  assert.equal(inputs.filter(s=>s.includes('xterm.js(')).length,1,'only headless replies, across page refresh');
  await page.getByRole('button',{name:'Session actions',exact:true}).click();
  await page.getByRole('combobox',{name:'Interface mode'}).selectOption('desktop');
  await page.setViewportSize({width:1280,height:900});
  const resizeDeadline=Date.now()+5000;
  while(session.cols<=80 && Date.now()<resizeDeadline) await new Promise(resolve=>setTimeout(resolve,25));
  assert.ok(session.cols>80,`desktop selection must resize the PTY beyond its mobile width: ${session.cols}`);
  const screen=await page.locator('.xterm-screen').boundingBox();
  await page.mouse.move(screen.x+2,screen.y+8);
  await page.mouse.down();
  await page.mouse.move(screen.x+220,screen.y+42,{steps:12});
  await page.mouse.up();
  const beforeF8=inputs.length;
  await page.keyboard.press('F8');
  await page.waitForFunction(()=>window.copiedSelections.length===1,{},{timeout:3000});
  const copied=await page.evaluate(()=>window.copiedSelections[0]);
  assert.match(copied,/fixture row/,'F8 copies the actual xterm selection');
  assert.ok(copied.split('\n').every(line=>line===line.trimEnd()),'F8 removes terminal padding');
  assert.equal(inputs.slice(beforeF8).join(''),'','F8 must not reach the running agent');
  await page.getByRole('button',{name:'Trim and copy terminal selection',exact:true}).click();
  await page.waitForFunction(()=>window.copiedSelections.length===2);
  assert.equal(await page.evaluate(()=>window.copiedSelections[1]),copied,'toolbar copies the same preserved selection');
  assert.deepEqual(errors,[],'no browser runtime errors');
  console.log('PASS: full mobile UI loads, sends multiline input once, refreshes without duplicate query replies expands the PTY on desktop, and F8/toolbar copy the terminal selection');
} finally { await browser?.close(); await server.close(); rmSync(dir,{recursive:true,force:true}); }
