  const text=sec().querySelector('.archive-status').textContent;
  assert.match(text,/Recording.*Warning: One source file is missing/);
  assert.ok(document.querySelector('#toast-session-archive').classList.contains('t-warn'));
  assert.match(document.querySelector('#toast-session-archive').textContent,/Recording continues/);
